# Shown: the header cards, a window of rows, and one row opened to its evidence. Hidden: the
# panels about coverage and attribution, which the run's own console already shows in the GIF.
_FOCUS = """<style>.panel,.warn,.note,.note2{display:none!important}</style>
<script>addEventListener('DOMContentLoaded',function(){
var rows=[].slice.call(document.querySelectorAll('tr.row'));
var i=rows.findIndex(function(r){return r.cells[0].textContent.trim()===%s});
if(i<0){document.title='ROW NOT FOUND';return}
rows.forEach(function(r,k){if(k<i-5||k>i+1){r.style.display='none'}});
rows[i].nextElementSibling.classList.add('open');});</script>"""


def _browser():
    for b in [os.environ.get("CHROME")] + BROWSERS:
        if b and (os.path.exists(b) or shutil.which(b)):
            return b
    raise SystemExit("no Chrome or Edge found; set CHROME to one")


def report(takes, out_path, row=REPORT_ROW):
    from PIL import Image
    out_dir = os.path.join(takes["work"], "qatration-out")
    src = os.path.join(out_dir, "report_%s.html" % NAME)
    html = io.open(src, encoding="utf-8").read()
    if ">%s<" % row not in html:
        raise SystemExit("row %s is not in the report" % row)
    focus = os.path.join(out_dir, "report_focus.html")
    io.open(focus, "w", encoding="utf-8").write(html.replace("</head>", _FOCUS % json.dumps(row) + "</head>", 1))
    shot = os.path.join(out_dir, "report_focus.png")
    subprocess.run([_browser(), "--headless=new", "--disable-gpu", "--mute-audio",
                    "--hide-scrollbars", "--window-size=1280,2400", "--virtual-time-budget=3000",
                    "--screenshot=" + shot, "file:///" + focus.replace("\\", "/")],
                   check=True, capture_output=True)
    im = Image.open(shot).convert("RGB")
    bg = im.getpixel((2, 2))
    px = im.load()
    # Cropped to what is drawn, with a margin: the page centres a column on a wide canvas.
    xs = [x for x in range(0, im.width, 4) if any(px[x, y] != bg for y in range(0, im.height, 8))]
    ys = [y for y in range(0, im.height, 4) if any(px[x, y] != bg for x in range(0, im.width, 8))]
    m = 22
    im.crop((max(xs[0] - m, 0), max(ys[0] - m, 0), min(xs[-1] + m, im.width),
             min(ys[-1] + m, im.height))).save(out_path, optimize=True)
    return Image.open(out_path).size


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("step", choices=["record", "render", "report", "all"])
    ap.add_argument("--work", default=os.path.join(os.path.expanduser("~"), "qatration-demo"),
                    help="the fresh folder the session runs in (default ~/qatration-demo; "
                         "emptied on record)")
    ap.add_argument("--qatration", default=shutil.which("qatration"),
                    help="the CLI to record (default: `qatration` on PATH)")
    ap.add_argument("--url", default=URL)
    ap.add_argument("--model", default=MODEL)
    a = ap.parse_args()
    if a.step in ("record", "all"):
        if not a.qatration:
            raise SystemExit("`qatration` is not on PATH; pip install it, or pass --qatration")
        record(a.work, a.qatration, a.url, a.model)
    takes = json.load(io.open(os.path.join(a.work, TAKES), encoding="utf-8"))
    if a.step in ("render", "all"):
        n, s = render(takes, os.path.join(SITE, "run.gif"))
        print("site/run.gif: %d frames, %.1f s" % (n, s))
    if a.step in ("report", "all"):
        print("site/report.png: %dx%d" % report(takes, os.path.join(SITE, "report.png")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
